#!/bin/sh
# Install pm1 for ONE user, CPU-only, from a checkout: virtualenv, command wrappers, optional background capture.
#   deploy/install.sh [--prefix DIR] [--db FILE] [--with-capture] [--dry-run]
#     --prefix DIR     where the wrappers go (default ~/.local/bin)
#     --db FILE        the database (default $XDG_STATE_HOME/pm1/memory.sqlite)
#     --with-capture   also install + start a systemd --user service that captures Codex / Claude Code sessions (Linux)
#     --dry-run        print what would be done, change nothing
# Nothing here needs a GPU service or a cloud account. Rerankers, GPU embedders and the Cursor judges are optional and
# are switched on with PM1_* settings (README: Configuration). It does NOT edit your agent configuration: it prints the
# registration snippets to paste.
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
PREFIX="$HOME/.local/bin"; DB=""; CAPTURE=0; DRY=0
while [ $# -gt 0 ]; do
  case "$1" in
    --prefix) PREFIX=$2; shift 2;; --db) DB=$2; shift 2;; --with-capture) CAPTURE=1; shift;; --dry-run) DRY=1; shift;;
    -h|--help) sed -n '2,11p' "$0"; exit 0;; *) echo "unknown option $1" >&2; exit 2;;
  esac
done
[ -n "$DB" ] || DB="${XDG_STATE_HOME:-$HOME/.local/state}/pm1/memory.sqlite"
VENV="$ROOT/.venv"
run() { if [ $DRY -eq 1 ]; then echo "would: $*"; else "$@"; fi; }
write() {  # file mode  (content on stdin)
  if [ $DRY -eq 1 ]; then echo "would write $1:"; sed 's/^/    /'; else mkdir -p "$(dirname "$1")"; cat >"$1"; chmod "$2" "$1"; echo "wrote $1"; fi
}

echo "pm1 checkout: $ROOT"; echo "database:     $DB"; echo "wrappers:     $PREFIX"
command -v python3 >/dev/null || { echo "python3 (3.11+) is required" >&2; exit 1; }
python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3, 11) else 1)' || { echo "python 3.11+ is required" >&2; exit 1; }
if [ ! -x "$VENV/bin/python" ]; then run python3 -m venv "$VENV"; fi
run "$VENV/bin/pip" install --quiet -e "$ROOT[local-embed]" || run "$VENV/bin/pip" install --quiet -e "$ROOT"
run mkdir -p "$(dirname "$DB")" "$PREFIX"

# every wrapper pins the one database and the virtualenv; settings still come from the environment or ~/.config/pm1/config.toml
for spec in "pm1-mcp:exec \"$VENV/bin/pm1-mcp\" \"\$@\"" \
            "pm1-cc-hook:exec \"$VENV/bin/python\" \"$ROOT/src/pm1/cc_hook.py\" \"\$@\"" \
            "pm1-rule:exec \"$VENV/bin/python\" -c \"from pm1.rules import cli; cli()\" \"\$@\"" \
            "pm1-docs:exec \"$VENV/bin/pm1-docs\" \"\$@\"" ; do
  name=${spec%%:*}; body=${spec#*:}
  write "$PREFIX/$name" 755 <<WRAP
#!/bin/sh
# generated by pm1 deploy/install.sh
export PM1_DB="\${PM1_DB:-$DB}"
$body
WRAP
done

if [ $CAPTURE -eq 1 ]; then
  UNIT="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user/pm1-capture.service"
  write "$UNIT" 644 <<UNIT
[Unit]
Description=pm1 passive session capture (Codex rollouts, Claude Code transcripts)

[Service]
Type=simple
WorkingDirectory=$ROOT
Environment=PM1_DB=$DB
ExecStart=$VENV/bin/pm1-capture watch -i 60
Restart=on-failure
RestartSec=30
Nice=10
IOSchedulingClass=idle

[Install]
WantedBy=default.target
UNIT
  run systemctl --user daemon-reload
  run systemctl --user enable --now pm1-capture.service
fi

cat <<MSG

Done. Register pm1 with your agents (paste; nothing was edited for you):

  Claude Code:   claude mcp add pm1 -- $PREFIX/pm1-mcp
  Codex:         add to ~/.codex/config.toml
                   [mcp_servers.pm1]
                   command = "$PREFIX/pm1-mcp"
  Cursor:        add to ~/.cursor/mcp.json   {"mcpServers": {"pm1": {"command": "$PREFIX/pm1-mcp"}}}

  Claude Code hooks (rules + lessons pushed at the right moment) are optional; see README "Claude Code hooks"
  (the wrapper is $PREFIX/pm1-cc-hook). Approve rules in your own terminal: $PREFIX/pm1-rule pending
Check:  PM1_BIN=$PREFIX PM1_DB=$DB $ROOT/deploy/smoke.sh
MSG
